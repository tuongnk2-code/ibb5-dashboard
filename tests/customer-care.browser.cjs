const assert=require('node:assert/strict');
const fs=require('node:fs');
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const {fixture,ids}=require('./customer-care-fixture.cjs');
(async()=>{
  const {createServer}=await import('../node_modules/vite/dist/node/index.js');
  const server=await createServer({server:{host:'127.0.0.1',port:5268,strictPort:true}});await server.listen();
  const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'});
  try{for(const [width,role] of [[390,'staff'],[320,'staff'],[1440,'manager']]){
    const {request,tables,people}=await fixture(),me=people.find(p=>p.id===(role==='staff'?ids.STAFF:ids.MANAGER));
    const page=await browser.newPage({viewport:{width,height:950}}),errors=[];
    page.on('pageerror',e=>errors.push(e.message));page.on('dialog',dialog=>dialog.accept());
    await page.route('**/js/auth.js',r=>r.fulfill({contentType:'application/javascript',body:`export async function getSession(){return {access_token:'${me.id}'}};export async function signOut(){};export async function callAdminUsersApi(){return {profiles:[]}}`}));
    await page.route('**/js/api.js',r=>r.fulfill({contentType:'application/javascript',body:'import * as data from "/js/mockData.sample.js";export async function fetchDashboardData(){return data}'}));
    await page.route('**/js/app-gate.js',r=>r.fulfill({contentType:'application/javascript',body:`window.IBB5_CURRENT_PROFILE=${JSON.stringify(me)};document.getElementById('loginScreen').style.display='none';document.getElementById('appShell').style.display='';await import('/js/main.js');`}));
    await page.route('**/api/customer-care',async r=>{const response=await request(me.id,r.request().method(),r.request().method()==='POST'?r.request().postDataJSON():undefined);await r.fulfill({status:response.status,json:response.body});});
    await page.route('https://**/*',r=>r.abort());
    await page.goto('http://127.0.0.1:5268/#customerCare');
    await page.locator('.cc-empty').waitFor();
    await page.locator('.cc-tabs [data-tab="customers"]').click();
    await page.locator('[data-edit="A1"]').click();
    const contact=page.locator('[data-contact-dialog]');
    await contact.locator('[name="phone"]').fill('0990000001');await contact.locator('[name="consent"]').check();
    await contact.getByRole('button',{name:'Lưu thông tin KH'}).click();await contact.waitFor({state:'hidden'});
    assert.equal(tables.care_contacts.find(c=>c.contract_id==='A1').phone,'0990000001');
    await page.locator('[data-cc="new"]').click();const form=page.locator('[data-campaign-dialog]');
    await form.locator('[name="owner_id"]').selectOption(ids.STAFF);
    await form.locator('[name="name"]').fill('Chăm sóc thử nghiệm');
    await form.locator('[name="when"]').fill('2026-11-21T09:00');
    await form.locator('[name="repeat_days"]').selectOption('7');
    await form.locator('[data-pick-all]').click();
    assert.match(await form.locator('[data-picked]').textContent(),/^2 KH/);
    assert.match(await form.locator('[data-preview]').textContent(),/Nguyễn Khách A/);
    assert.equal(await form.locator('.cc-picker img').count(),0,'customer names escaped');
    if(width<600)assert.ok(await form.evaluate(el=>el.scrollWidth<=el.clientWidth+1),'dialog fits phone');
    await form.locator('[type="submit"]').click();await form.waitFor({state:'hidden'});
    await page.locator('.cc-detail .cc-task').first().waitFor();
    assert.equal(tables.care_results.length,0,'opening campaign never marks messages sent');
    assert.equal(await page.locator('[data-task="A1"] a').getAttribute('href'),'https://zalo.me/0990000001');
    await page.locator('[data-sent="A1"]').click();
    await page.waitForFunction(()=>document.querySelector('[data-task="A1"] .cc-badge').textContent==='Đã gửi');
    await page.locator('[data-task="A2"] [data-result]').selectOption('optout');
    await page.locator('[data-task="A2"] [data-note]').fill('KH yêu cầu dừng chăm sóc');
    await page.locator('[data-save-result="A2"]').click();
    await page.waitForFunction(()=>document.querySelector('[data-task="A2"] .cc-badge').textContent==='Từ chối nhận tin');
    assert.equal(tables.care_contacts.find(c=>c.contract_id==='A2').consent,false);
    await page.locator('[data-cc="finish"]').click();
    await page.waitForFunction(()=>document.querySelector('.cc-detail h3').textContent.includes('Kỳ 2'));
    assert.equal(tables.care_results.length,2);
    assert.match(await page.locator('[data-task="A2"]').textContent(),/KH được bỏ qua/);
    await page.locator('.cc-tabs [data-tab="reports"]').click();
    assert.match(await page.locator('.cc-stats').textContent(),/Lượt KH đã gửi1/);
    const download=page.waitForEvent('download');await page.locator('[data-cc="csv"]').click();const csv=fs.readFileSync(await (await download).path(),'utf8');assert.match(csv,/KH yêu cầu dừng chăm sóc/);
    await page.reload();await page.locator('.cc-campaign').waitFor();await page.locator('.cc-campaign').click();
    assert.match(await page.locator('.cc-detail h3').textContent(),/Kỳ 2/,'campaign persists after reload');
    if(width<600){assert.ok(await page.locator('#customerCare').evaluate(el=>el.scrollWidth<=el.clientWidth+1),'panel fits phone');}
    if(process.env.CARE_SCREENSHOT_DIR)await page.screenshot({path:`${process.env.CARE_SCREENSHOT_DIR}/customer-care-${width}.png`});
    assert.deepEqual(errors,[]);await page.close();
    console.log(`PASS CSKH ${role} ${width}px: contact → campaign → explicit sent/result → next round → report/CSV → reload`);
  }}finally{await browser.close();await server.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
